def _pick(items: list, chapter: int, stride: int) -> str:
    """用质数步长在列表中旋转选取，确保相邻章节不重复"""
    return items[((chapter - 1) * stride) % len(items)]


def _get_stage(chapter_number: int) -> tuple:
    """根据章节号返回 (阶段编号, 阶段名, 阶段描述)"""
    if chapter_number <= 20:
        return 1, "同事博弈", "初入职场/底层翻身，对手是同级同事和直接竞争者。主角需要从零建立人脉和信任。"
    elif chapter_number <= 50:
        return 2, "主管对抗", "中层突破，对手是直属领导和部门管理者。主角开始触碰权力边界。"
    elif chapter_number <= 100:
        return 3, "派系周旋", "公司政治阶段，对手是多方势力。主角需要在复杂利益中左右逢源。"
    elif chapter_number <= 160:
        return 4, "高层博弈", "高层决策阶段，对手是董事/合伙人/外部势力。筹码变大，格局升级。"
    else:
        return 5, "行业称王", "行业级博弈，对手是行业巨头和规则本身。主角开始定义游戏规则。"


def generate_event_directive(chapter_number: int) -> str:
    """为指定章节动态生成事件指令 — 6维组合，相邻章节绝不重复

    组合原理：6个维度用不同的质数步长旋转，
    最小公倍周期 = 8×18×20×18×12×14 = 4,354,560 章才会完全重复。
    """
    stage_id, stage_name, stage_desc = _get_stage(chapter_number)
    opponents = _OPPONENTS.get(stage_id, _OPPONENTS[1])

    opponent = _pick(opponents, chapter_number, 3)
    trigger = _pick(_TRIGGERS, chapter_number, 7)
    weapon = _pick(_WEAPONS, chapter_number, 11)
    scene = _pick(_SCENES, chapter_number, 5)
    pattern = _pick(_PATTERNS, chapter_number, 13)
    reward = _pick(_REWARDS, chapter_number, 9)

    return (
        f"【第{chapter_number}章 · 动态事件指令】\n"
        f"阶段: {stage_name} — {stage_desc}\n"
        f"对手: {opponent}\n"
        f"冲突触发: {trigger}\n"
        f"规则武器: {weapon}\n"
        f"爆发场景: {scene}\n"
        f"反击模式: {pattern}\n"
        f"胜利收获: {reward}\n"
        f"\n"
        f"━━━ 重要 ━━━\n"
        f"以上6个维度是创意骨架，你必须将它们融合成一个有机的、连贯的故事事件。\n"
        f"不要机械地逐条对应，而是让它们自然地编织在一起。\n"
        f"如果某个维度与当前故事线明显矛盾，可以灵活替换为同阶段的其他合理选项。\n"
        f"核心原则：本章事件必须与前面所有章节在'对手+手段+结局'三要素中至少两项不同。"
    )

